/** 取某周数据；越界或缺失时回落到最近的合法周 */
export function getWeekEntry(week: number): WeekEntry {
  const w = Math.min(Math.max(Math.round(week), MIN_WEEK), MAX_WEEK)
  return WEEK_DATA[w] ?? WEEK_DATA[MIN_WEEK]
}

/** 取概述首句（按中文句读截断到 maxlen 字内），供入口卡单行摘要 */
function firstSentence(text: string, maxlen = 42): string {
  const m = text.split(/[。！？;]/)[0] || text
  return m.length > maxlen ? m.slice(0, maxlen - 1) + '…' : m
}

/** 首页入口卡 - 宝宝变化摘要（随当前孕周变化） */
export function weekBabyTeaser(week: number): string {
  return firstSentence(getWeekEntry(week).baby)
}

/** 首页入口卡 - 妈妈变化摘要（随当前孕周变化） */
export function weekMomTeaser(week: number): string {
  return firstSentence(getWeekEntry(week).mom)
}
